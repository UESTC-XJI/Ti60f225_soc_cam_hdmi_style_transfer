"""Integer-only, reproducible grayscale curve and RGB headroom lookup tables."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ANCHORS = [(0, 0), (16, 16), (32, 64), (64, 120), (96, 160),
           (128, 188), (160, 212), (192, 232), (224, 248), (255, 255)]

def target_y(y):
    for (x0, y0), (x1, y1) in zip(ANCHORS, ANCHORS[1:]):
        if x0 <= y <= x1:
            return y0 + (y - x0) * (y1 - y0) // (x1 - x0)
    raise ValueError(y)

def extra_gain(y):
    return ((target_y(y) - y) * 256 + y - 1) // y if y else 0

def cap_gain(maximum):
    return min(512, 255 * 256 // maximum) if maximum else 512

if __name__ == '__main__':
    gains = [extra_gain(y) for y in range(256)]
    caps = [cap_gain(y) for y in range(256)]
    # Q8.8 rounding can otherwise reverse a gray ramp by one code at some
    # intermediate strengths. Raise the next gain minimally to remove reversals.
    for y in range(1, 256):
        while any(
            y * min(256 + gains[y] * s // 128, caps[y]) // 256 <
            (y - 1) * min(256 + gains[y - 1] * s // 128, caps[y - 1]) // 256
            for s in range(129)
        ):
            gains[y] += 1
            assert gains[y] <= 256
    assert all(0 <= g <= 256 for g in gains)
    for strength in range(129):
        outputs = [y * min(256 + gains[y] * strength // 128, caps[y]) // 256 for y in range(256)]
        assert all(a <= b for a, b in zip(outputs, outputs[1:])), (strength, outputs)
        assert outputs[:17] == list(range(17))
    for name, values in [('lift_gain.mem', gains), ('lift_cap.mem', caps)]:
        (ROOT / 'rtl/isp' / name).write_text(''.join(f'{value:03x}\n' for value in values), encoding='ascii')
    # Explicit constant cases avoid tool-specific initialization of read-only
    # arrays. The .mem copies remain independent fixtures for simulation.
    functions = ['// Generated by tools/generate_lift_tables.py; do not edit.\n']
    for name, width, values, default in [
        ('lift_extra_lookup', 9, gains, 0), ('lift_cap_lookup', 10, caps, 256)
    ]:
        functions += [f'function [{width - 1}:0] {name};\n', '  input [7:0] code;\n', '  begin\n', '    case(code)\n']
        functions += [f"      8'd{i}: {name}={width}'d{value};\n" for i, value in enumerate(values)]
        functions += [f"      default: {name}={width}'d{default};\n", '    endcase\n', '  end\n', 'endfunction\n']
    (ROOT / 'rtl/isp/lift_tables.vh').write_text(''.join(functions), encoding='ascii')
    print('Generated 256-entry gain/cap tables; all 129 strength curves monotonic.')
